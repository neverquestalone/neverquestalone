-- Markdown to the window's text, as the app renders a reply
-- (bridge/app/render.mjs markdownToWow): headings gold, bullets •, code gray
-- and indented, tables as rows; every | doubled.
---------------------------------------------------------------------------

local GOLD, GRAY, CLOSE = "|cffffd100", "|cffa0a0a0", "|r"

-- A pair of marks (** __ ~~) around text that starts and ends with a non-space.
-- [code health AD-02] A closing mark is one after a non-space, wherever the opener is:
-- once an opener finds none, no later opener can (each looks in less of the same
-- text), so the rest goes as it is. One pass, where a 60 KB line of unclosed marks
-- looked again from every opener and froze the client for seconds.
local function Pair(s, mark)
	local out, i, w = {}, 1, #mark
	while true do
		local a = s:find(mark, i, true)
		if not a then break end
		local b, inner = a + w, nil
		if s:sub(a + w, a + w):match("%S") then
			b = s:find(mark, a + w + 1, true)
			while b and not s:sub(b - 1, b - 1):match("%S") do b = s:find(mark, b + 1, true) end
			if not b then break end
			inner = s:sub(a + w, b - 1)
		end
		if inner then
			out[#out + 1] = s:sub(i, a - 1) .. inner
			i = b + w
		else
			out[#out + 1] = s:sub(i, a + w - 1)
			i = a + w
		end
	end
	out[#out + 1] = s:sub(i)
	return table.concat(out)
end

-- One-mark emphasis (* or _): not after a word character or the mark, not
-- before one, no mark or line break inside.
local function Single(s, mark)
	local word = mark == "*" and "[%w_%*]" or "[%w_]"
	local out, i = {}, 1
	while true do
		local a = s:find(mark, i, true)
		if not a then break end
		local before = a > 1 and s:sub(a - 1, a - 1) or ""
		local b = s:find(mark, a + 1, true)
		local inner = b and s:sub(a + 1, b - 1)
		if inner and inner ~= "" and not before:match(word) and inner:match("^%S") and inner:match("%S$")
			and not inner:find("\n", 1, true) and not s:sub(b + 1, b + 1):match("[%w_]") then
			out[#out + 1] = s:sub(i, a - 1) .. inner
			i = b + 1
		else
			out[#out + 1] = s:sub(i, a)
			i = a + 1
		end
	end
	out[#out + 1] = s:sub(i)
	return table.concat(out)
end

-- Inline markdown to plain text (no escapes added).
local function InlinePlain(s)
	s = tostring(s or "")
	s = s:gsub("!%[([^%]]*)%]%(([^%)%s]+)[^%)]*%)", function(alt, url)
		return "[image" .. (alt ~= "" and (": " .. alt) or "") .. "] (" .. url .. ")"
	end)
	s = s:gsub("%[([^%]]+)%]%(([^%)%s]+)[^%)]*%)", function(t, url) return t == url and url or (t .. " (" .. url .. ")") end)
	s = s:gsub("<(https?://[^>%s]+)>", "%1")
	s = s:gsub("`([^`]+)`", "%1")
	s = Pair(s, "**")
	s = Pair(s, "__")
	s = Single(s, "*")
	s = Single(s, "_")
	s = Pair(s, "~~")
	return s
end
P.InlinePlain = InlinePlain

local function TableRow(l) return l:match("^%s*|.*|%s*$") ~= nil end
local function TableSep(l)
	local body = Trim(l):gsub("^|", ""):gsub("|$", "")
	if body == "" then return false end
	for cell in (body .. "|"):gmatch("([^|]*)|") do
		if not cell:match("^%s*:?%-%-%-+:?%s*$") then return false end
	end
	return true
end
local function Cells(l)
	local out = {}
	local body = Trim(l):gsub("^|", ""):gsub("|$", "")
	for cell in (body .. "|"):gmatch("([^|]*)|") do out[#out + 1] = InlinePlain(Trim(cell)) end
	return out
end

-- The one sentence under a table (the window can't draw tables).
P.TABLE_NOTE = "(A table doesn't fit here, so its rows follow. Your AI's page shows it whole.)"

function P.Markdown(md)
	local lines = Lines(tostring(md or ""):gsub("\r\n?", "\n"))
	local out, inCode, i = {}, false, 1
	while i <= #lines do
		local line = lines[i]
		if line:match("^%s*```") or line:match("^%s*~~~") then
			inCode = not inCode
		elseif inCode then
			out[#out + 1] = line:match("%S") and ("    " .. GRAY .. Pipes(line) .. CLOSE) or ""
		elseif TableRow(line) and lines[i + 1] and TableSep(lines[i + 1]) then
			local rows = { Cells(line) }
			i = i + 1
			while lines[i + 1] and TableRow(lines[i + 1]) do
				i = i + 1
				rows[#rows + 1] = Cells(lines[i])
			end
			out[#out + 1] = GRAY .. Pipes(P.TABLE_NOTE) .. CLOSE
			for r = 1, math.min(#rows, 6) do out[#out + 1] = Pipes(table.concat(rows[r], " · ")) end
			if #rows > 6 then
				local more = #rows - 6
				out[#out + 1] = GRAY .. Pipes(more == 1 and "… 1 more row" or string.format("… %d more rows", more)) .. CLOSE
			end
		else
			local hashes, head = line:match("^%s*(#+)%s+(.-)%s*#*%s*$")
			local bare = line:gsub("%s", "")
			local indent, mark, rest = line:match("^(%s*)[-*+]%s+%[([ xX])%]%s+(.*)$")
			local bIndent, bullet = line:match("^(%s*)[-*+]%s+(.*)$")
			local quote = line:match("^%s*>%s?(.*)$")
			if hashes and #hashes <= 6 then
				out[#out + 1] = GOLD .. Pipes(InlinePlain(head)) .. CLOSE
			elseif #bare >= 3 and (bare:match("^%-+$") or bare:match("^%*+$") or bare:match("^_+$")) then
				out[#out + 1] = "———"
			elseif indent then
				out[#out + 1] = string.rep("  ", math.floor(#indent / 2)) .. (mark == " " and "☐" or "☑") .. " " .. Pipes(InlinePlain(rest))
			elseif bIndent then
				out[#out + 1] = string.rep("  ", math.floor(#bIndent / 2)) .. "• " .. Pipes(InlinePlain(bullet))
			elseif quote then
				out[#out + 1] = GRAY .. "  " .. Pipes(InlinePlain(quote)) .. CLOSE
			else
				out[#out + 1] = Pipes(InlinePlain(line))
			end
		end
		i = i + 1
	end
	local s = table.concat(out, "\n"):gsub("\n\n\n+", "\n\n")
	return Trim(s)
end

