local ARRAY = setmetatable({}, { __mode = "k" })
P.IsArray = function(t) return type(t) == "table" and ARRAY[t] == true end

local function Utf8(cp)
	if cp < 0x80 then return string.char(cp) end
	if cp < 0x800 then return string.char(0xC0 + math.floor(cp / 0x40), 0x80 + cp % 0x40) end
	if cp < 0x10000 then
		return string.char(0xE0 + math.floor(cp / 0x1000), 0x80 + math.floor(cp / 0x40) % 0x40, 0x80 + cp % 0x40)
	end
	return string.char(0xF0 + math.floor(cp / 0x40000), 0x80 + math.floor(cp / 0x1000) % 0x40,
		0x80 + math.floor(cp / 0x40) % 0x40, 0x80 + cp % 0x40)
end

local ESCAPES = { ['"'] = '"', ["\\"] = "\\", ["/"] = "/", b = "\b", f = "\f", n = "\n", r = "\r", t = "\t" }

-- Returns true, value (value may be nil for null) or false, why.
function P.JSON(s)
	s = tostring(s or "")
	local i, n, depth = 1, #s, 0
	local function fail(why) error({ json = why }, 0) end
	local function skip() i = s:find("[^ \t\r\n]", i) or n + 1 end
	local value
	local function str()
		i = i + 1
		local out = {}
		while true do
			local j = s:find('["\\%c]', i)
			if not j then fail("a string doesn't end") end
			out[#out + 1] = s:sub(i, j - 1)
			local c = s:sub(j, j)
			if c == '"' then
				i = j + 1
				return table.concat(out)
			end
			if c ~= "\\" then fail("a control character in a string") end
			local e = s:sub(j + 1, j + 1)
			if e == "u" then
				local hex = s:match("^%x%x%x%x", j + 2)
				if not hex then fail("a bad \\u escape") end
				local cp = tonumber(hex, 16)
				i = j + 6
				if cp >= 0xD800 and cp <= 0xDBFF then
					local lo = s:match("^\\u(%x%x%x%x)", i)
					local low = lo and tonumber(lo, 16)
					if low and low >= 0xDC00 and low <= 0xDFFF then
						cp = 0x10000 + (cp - 0xD800) * 0x400 + (low - 0xDC00)
						i = i + 6
					else
						cp = 0xFFFD
					end
				elseif cp >= 0xDC00 and cp <= 0xDFFF then
					cp = 0xFFFD
				end
				out[#out + 1] = Utf8(cp)
			else
				local v = ESCAPES[e]
				if not v then fail("a bad escape") end
				out[#out + 1] = v
				i = j + 2
			end
		end
	end
	local function num()
		local m = s:match("^-?%d+%.?%d*[eE][-+]?%d+", i) or s:match("^-?%d+%.?%d*", i)
		local v = m and tonumber(m)
		if not v then fail("a bad number") end
		i = i + #m
		return v
	end
	function value()
		skip()
		local c = s:sub(i, i)
		if c == "{" or c == "[" then
			depth = depth + 1
			if depth > JSON_DEPTH then fail("too deep") end
			i = i + 1
			local t, close, k = {}, c == "{" and "}" or "]", 0
			skip()
			if s:sub(i, i) == close then
				i = i + 1
			else
				while true do
					skip()
					if c == "{" then
						if s:sub(i, i) ~= '"' then fail("a key isn't a string") end
						local key = str()
						skip()
						if s:sub(i, i) ~= ":" then fail("a key has no value") end
						i = i + 1
						t[key] = value()
					else
						local v = value()
						if v ~= nil then
							k = k + 1
							t[k] = v
						end
					end
					skip()
					local d = s:sub(i, i)
					i = i + 1
					if d == close then break end
					if d ~= "," then fail("a list isn't separated by commas") end
				end
			end
			if c == "[" then ARRAY[t] = true end
			depth = depth - 1
			return t
		elseif c == '"' then
			return str()
		elseif s:sub(i, i + 3) == "true" then
			i = i + 4
			return true
		elseif s:sub(i, i + 4) == "false" then
			i = i + 5
			return false
		elseif s:sub(i, i + 3) == "null" then
			i = i + 4
			return nil
		elseif c:match("^[-%d]$") then
			return num()
		end
		fail("an unexpected character")
	end
	local ok, v = pcall(function()
		local r = value()
		skip()
		if i <= n then fail("text after the value") end
		return r
	end)
	if ok then return true, v end
	return false, type(v) == "table" and v.json or "unreadable"
end

