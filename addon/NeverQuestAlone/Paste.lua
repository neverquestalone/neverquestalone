{"op":"set","layer":"route","title":"Westfall quests","ordered":true,"points":[{"m":1436,"x":56.3,"y":47.5,"label":"1. Sentinel Hill","kind":"turnin","note":"Turn in Westfall Stew","q":[36]}]}
"m" is the map's id from the game data below. With "ordered":true the points are a numbered route the game leads them along, stop by stop. "kind" is one of quest, turnin, kill, loot, object, explore, npc, trainer, vendor, dungeon, flight, ore, herb, poi. "q" lists the quest ids for that stop. "note" says what to do at the stop, never how far or how close it is or that it's the nearest: the game shows the live distance. {"op":"clear","layer":"route"} takes a layer off.
- wowrefs, the ids you name, so they show as game links: {"q":[36],"i":[2140],"s":[8017]}
- wowweights, stat weights for their build, so the game rates gear for them: {"str":1.0,"sta":0.8,"agi":0.4}
- wowchips, up to 3 short questions they might ask next, one per line.
Only draw on the map when they ask for a route or a place, and say in your reply what you drew.]]

local function Field(o, k)
	if type(o) ~= "table" then return nil end
	if type(o._o) ~= "table" then return o[k] end
	for _, kv in ipairs(o._o) do
		if kv[1] == k then return kv[2] end
	end
end

-- Where gear is worn, by the game's inventory ids (INVSLOT_HEAD 1 to INVSLOT_TABARD 19).
local GEAR_PLACES = { "head", "neck", "shoulders", "shirt", "chest", "waist", "legs", "feet", "wrists", "hands",
	"finger 1", "finger 2", "trinket 1", "trinket 2", "back", "main hand", "off hand", "ranged", "tabard" }

local function Num(v)
	v = tonumber(v)
	if not v then return "?" end
	if v == math.floor(v) then return string.format("%d", v) end
	return string.format("%.1f", v)
end

-- The game data, as plain lines. The lines the app gets (Chats.GameContext),
-- the character's without its name, realm and guild; then the quest log, its
-- spots on this map and the gear, from the companion's reading of the game.
function P.GameData()
	local lines = {}
	local ctx = ns.Chats.GameContext and ns.Chats.GameContext() or ""
	local hasQuests = false
	for _, line in ipairs(Lines(ctx)) do
		if line:find("^Character: ") then
			local level, race, class = ns.Try(UnitLevel, "player"), ns.Try(UnitRace, "player"), ns.Try(UnitClass, "player")
			local faction = ns.Try(UnitFactionGroup, "player")
			local desc = {}
			if level then desc[#desc + 1] = "level " .. tostring(level) end
			if race then desc[#desc + 1] = tostring(race) end
			if class then desc[#desc + 1] = tostring(class) end
			line = #desc > 0 and ("Character: " .. table.concat(desc, " ") .. (faction and (" (" .. tostring(faction) .. ")") or "")) or nil
		elseif line:find("^Quest log") then
			line = nil
		end
		if line and line:match("%S") then lines[#lines + 1] = line end
	end
	local g = ns.Companion and ns.Companion.Call("Gather") or nil
	local quests = type(g) == "table" and g.quests or nil
	if type(quests) == "table" and #quests > 0 then
		lines[#lines + 1] = "Quest log (id, level, title, then objectives as have/need; * means ready to turn in):"
		for _, q in ipairs(quests) do
			local objs = {}
			for _, o in ipairs(type(q.obj) == "table" and q.obj or {}) do
				objs[#objs + 1] = string.format("%s %s/%s", tostring(o.text or ""), Num(o.have), Num(o.need))
			end
			lines[#lines + 1] = string.format("%s%s L%s %s%s", Num(q.id), q.complete and "*" or "", Num(q.level), tostring(q.title or ""),
				#objs > 0 and (": " .. table.concat(objs, ", ")) or "")
		end
		hasQuests = true
	end
	-- Where quest chains lead (Chains.lua): the log's, and those the character can start near their level.
	if ns.Chains then
		local chained = {}
		for _, q in ipairs(type(quests) == "table" and quests or {}) do
			if type(q.chain) == "table" then chained[#chained + 1] = string.format("%s: %s", Num(q.id), ns.Chains.Words(q.chain)) end
		end
		if #chained > 0 then
			lines[#lines + 1] = string.format("Quest chains in the log (quest id: step, where the chain leads, the next quest): %s", table.concat(chained, "; "))
		end
		local starts = {}
		for _, st in ipairs(type(g) == "table" and g.chainStarts or {}) do
			local facts = { step = 1 }
			for _, kv in ipairs(type(st) == "table" and st._o or {}) do facts[kv[1]] = kv[2] end
			-- Named for each place: 1 quest id, 2 its title (when the game has it), 3 level, 4 the zone (when
			-- the game names it), 5 the chain in words.
			starts[#starts + 1] = string.format("%s%s, level %s%s: %s", Num(facts.id), facts.title and (" " .. tostring(facts.title)) or "",
				Num(facts.level), facts.zone and (", " .. tostring(facts.zone)) or "", ns.Chains.Words(facts))
		end
		if #starts > 0 then
			lines[#lines + 1] = string.format("Quest chains they can start near their level (quest id, title, level, zone: step, where the chain leads, the next quest): %s", table.concat(starts, "; "))
		end
	end
	local poi = type(g) == "table" and g.poi or nil
	if type(poi) == "table" and #poi > 0 then
		local spots = {}
		for _, p in ipairs(poi) do
			spots[#spots + 1] = string.format("%s at %s, %s on map %s", Num(Field(p, "id")), Num(Field(p, "x")), Num(Field(p, "y")), Num(Field(p, "map")))
		end
		lines[#lines + 1] = string.format("Where the game shows quest objectives (quest id at x, y): %s", table.concat(spots, "; "))
	end
	local gear = type(g) == "table" and g.gear or nil
	if type(gear) == "table" and #gear > 0 then
		local items = {}
		for _, it in ipairs(gear) do
			local where = GEAR_PLACES[tonumber(Field(it, "slot")) or 0] or Num(Field(it, "slot"))
			-- Named for each place: 1 where, 2 item id, 3 item level.
			items[#items + 1] = string.format("%s: item %s (item level %s)", where, Num(Field(it, "id")), Num(Field(it, "ilvl")))
		end
		lines[#lines + 1] = string.format("Gear worn: %s", table.concat(items, "; "))
	end
	if not hasQuests then
		-- Without the companion's reading, the quest ids the app gets.
		for _, line in ipairs(Lines(ctx)) do
			if line:find("^Quest log") then lines[#lines + 1] = line end
		end
	end
	return table.concat(lines, "\n")
end

-- The message to copy: the mark, the instructions, the game data, the words.
function P.Compose(entry)
	local parts = { P.MARK, Instructions() }
	local data = (entry and not entry.bare and ns.db.settings.context) and P.GameData() or ""
	if data ~= "" then
		parts[#parts + 1] = string.format("Game data, read from the game just now:\n%s", data)
	else
		parts[#parts + 1] = "No game data came with this message."
	end
	parts[#parts + 1] = string.format("The player's message:\n%s", tostring(entry and entry.text or ""))
	return table.concat(parts, "\n\n")
end

