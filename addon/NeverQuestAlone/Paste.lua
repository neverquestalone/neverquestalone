		if chat then P.Stop(chat, ui.key) end
	end)
	ui.stop:SetPoint("BOTTOMLEFT", f, "BOTTOMLEFT", PAD, 14)
	ui.use = ns.UI.Button(f, "Use Reply", 110, function() P.UseBox(false) end)
	ui.use:SetPoint("RIGHT", ui.close, "LEFT", -8, 0)
	-- What each does to the waiting message: Close keeps it, Stop drops it.
	for b, tip in pairs({
		[ui.close] = { title = "Close", key = "Esc", text = "Closes this window. Your message keeps waiting for its reply.", note = "Paste Reply in the HUD or /nqa paste brings it back." },
		[ui.stop] = { title = "Stop", text = "Drops this message: it won't get a reply." },
		[ui.use] = { title = "Use Reply", text = "Reads the reply under step 2. A paste is read by itself." },
	}) do
		b:SetScript("OnEnter", function(self) ns.Tip(self, tip, "ANCHOR_TOP") end)
		b:SetScript("OnLeave", function() if GameTooltip then GameTooltip:Hide() end end)
	end
	ui.frame = f
	return f
end

-- Which chat the window is open for, or nil.
function P.ShownFor()
	return ui.frame and ui.frame:IsShown() and ui.chat or nil
end

function P.Close()
	if ui.frame then ui.frame:Hide() end
end

-- Open the window for a chat's waiting message (that chat's newest, or with
-- no chat the newest in any chat). The first time, the message is selected
-- to copy; after that (Paste Reply, /bones paste), the cursor waits in step 2
-- for the reply. Returns false when no message waits.
function P.Open(chatId, key)
	local chat, p
	if chatId then
		chat = ns.Chats.Find(chatId)
		p = chat and P.Waiting(chat, key)
	else
		chat, p = P.Newest()
	end
	local entry = p and EntryOf(chat, p)
	if not entry then return false end
	Build()
	local again = p.opened
	p.opened = true
	local sameKey = ui.key == p.key
	ui.chat, ui.key = chat.id, p.key
	ui.message = P.Compose(entry)
	ui.copied = nil
	ui.hint1:SetText(string.format(P.Named(entry.bare
		and "Your message is selected, with how NeverQuestAlone should answer. Press %s, then paste it into ChatGPT, Claude or another AI."
		or "Your message is selected, with your game data and how NeverQuestAlone should answer. Press %s, then paste it into ChatGPT, Claude or another AI."), Key("C")))
	ui.hint2:SetText(string.format("Copy your AI's whole reply (most AIs have a Copy button under it), come back, click the box below and press %s.", Key("V")))
	ui.outBox:SetText(ui.message)
	if not again or not sameKey then
		ui.inBox:SetText("")
		ui.lastLen, ui.lastText = 0, ""
	end
	ui.frame:Show()
	if again then
		Say(string.format("Press %s to paste your AI's reply under step 2.", Key("V")))
		ui.inBox:SetFocus()
	else
		-- [C-133] Automatic fell back to Copy and Paste: say why, not the first-run words.
		local db = ns.db
		local fellBack = db and db.linked and type(db.settings) == "table" and db.settings.replies ~= "paste"
		Say(fellBack and P.FALLBACK or "Your AI's reply shows in the chat as soon as you paste it.")
		ui.outBox:SetFocus()
		ui.outBox:HighlightText()
	end
	return true
end

-- Read the reply box (a paste just arrived, or Use Reply).
function P.UseBox(auto)
	if not ui.frame or not ui.frame:IsShown() or not ui.chat then return false end
	local text = ui.inBox:GetText() or ""
	-- Read by itself only what looks like a reply (the TL;DR line the
	-- instructions ask for, or a block for the map): a link or a stray
	-- paste doesn't end the wait. A key goes on to be refused (AD-01).
	if auto and text:match("%S") and not (text:find("[Tt][Ll];?%s*[Dd][Rr]") or text:find("```wow", 1, true)) and not P.Parse(text).ours
		and not ns.Chats.KeyShaped(text) then
		-- [C-140, UX-W15] A few stray keys (a W meant for walking) are not a
		-- reply and not worth a click: the box is emptied and says what it is for,
		-- so the next paste is read clean. A paste fed one character at a time
		-- arrives whole before this read, and a link keeps the line below.
		if #text < 40 and not text:find("\n", 1, true) and not text:find("://", 1, true) and not text:find("www.", 1, true) then
			ui.inBox:SetText("")
			ui.lastLen, ui.lastText = 0, ""
			Say("This box takes your AI's reply: paste it here. Press Esc to play.")
			return false
		end
		Say("That doesn't look like your AI's reply: it has no TL;DR line. Click Use Reply to use it anyway.", true)
		return false
	end
	local ok, why = P.Receive(ui.chat, text, ui.key)
	if ok then
		ui.inBox:SetText("")
		ui.lastLen, ui.lastText = 0, ""
		return true
	end
	if why == "key" then
		-- [code health AD-01] (KY-10) Out of the box at once, with the refusal's own words.
		ui.inBox:SetText("")
		ui.lastLen, ui.lastText = 0, ""
		Say(ns.Chats.KeyRefused(), true)
	elseif why == "ours" then
		Say("That's your message from step 1. Copy your AI's reply and paste it here.", true)
	elseif why == "none" then
		P.Close()
		ns.Notify.Local("That message isn't waiting for a reply anymore.")
	elseif not auto then
		Say("Paste your AI's reply here first.", true)
	end
	return false
end
