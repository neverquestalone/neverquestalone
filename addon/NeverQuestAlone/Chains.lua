	f.text = f:CreateFontString(nil, "ARTWORK", "QuestFont")
	f.text:SetPoint("TOPLEFT")
	f.text:SetJustifyH("LEFT")
	if f.SetHyperlinksEnabled then f:SetHyperlinksEnabled(true) end
	f:SetScript("OnHyperlinkEnter", LinkEnter)
	f:SetScript("OnHyperlinkLeave", LinkLeave)
	f:SetScript("OnHyperlinkClick", LinkClick)
	-- Fades in with the page's parts (QuestInfo_FadeInAlphaDependentText's time).
	f.fade = f:CreateAnimationGroup()
	f.fade.anim = f.fade:CreateAnimation("Alpha")
	f.fade.anim:SetFromAlpha(0)
	f.fade.anim:SetToAlpha(1)
	if f.fade.SetToFinalAlpha then f.fade:SetToFinalAlpha(true) end
	lines[parent] = f
	return f
end

-- The page's parts that one of its templates puts right under the title (QuestInfo.xml).
local PARTS = { "QuestInfoQuestType", "QuestInfoDescriptionText", "QuestInfoObjectivesText", "QuestInfoRewardText",
	"QuestInfoTimerFrame", "QuestInfoObjectivesFrame", "QuestInfoSpecialObjectivesFrame", "QuestInfoRequiredMoneyFrame",
	"QuestInfoGroupSize", "QuestInfoDescriptionHeader", "QuestInfoSealFrame", "QuestInfoRewardsFrame", "QuestInfoSpacerFrame" }

-- The part this display put under the title, on this page, with its anchor; nil when none is.
local function Under(title, parent)
	for _, name in ipairs(PARTS) do
		local part = _G[name]
		if type(part) == "table" and type(part.GetPoint) == "function" and part:GetParent() == parent and part:IsShown() then
			local point, rel, relPoint, x, y = part:GetPoint(1)
			if rel == title then return part, { point, relPoint, x, y } end
		end
	end
end

-- The line's words, size and colour (the page's own body text's), at the template's width: in two
-- when it's wider than that (GetUnboundedStringWidth, documented on 1.60.1).
local function Draw(f, text, item, two)
	local body = QuestInfoDescriptionText
	if body and body.GetFontObject and body:GetFontObject() then f.text:SetFontObject(body:GetFontObject()) end
	if body and body.GetTextColor then f.text:SetTextColor(body:GetTextColor()) end
	f.text:SetWidth(f.width)
	f.text:SetText(text)
	if two then
		local w = Try(f.text.GetUnboundedStringWidth, f.text) or Try(f.text.GetStringWidth, f.text)
		if tonumber(w) and w > f.width then f.text:SetText(two) end
	end
	f:SetSize(f.width, math.max(1, f.text:GetStringHeight() or 0))
	f.item = item
	f:EnableMouse(item ~= nil) -- the reward's link takes the mouse; a dungeon's name doesn't
end

-- The line off its page, and the part it held back under the title where the game had put it.
local function TakeOff(f)
	f:Hide()
	local part, a = f.part, f.anchor
	f.part, f.anchor = nil, nil
	if part and a and QuestInfoTitleHeader and part:GetParent() == f:GetParent() then
		part:ClearAllPoints()
		part:SetPoint(a[1] or "TOPLEFT", QuestInfoTitleHeader, a[2] or "BOTTOMLEFT", a[3] or 0, a[4] or -GAP)
	end
end

local PAGES -- the templates the line goes on, once the game has them
function C.OnDisplay(template, parent)
	if type(parent) ~= "table" then return end
	PAGES = PAGES or { [QUEST_TEMPLATE_DETAIL or 1] = true, [QUEST_TEMPLATE_LOG or 2] = true, [QUEST_TEMPLATE_MAP_DETAILS or 3] = true }
	-- The game's parts are shared: a page whose title went to another page has nothing for a line to sit
	-- under. One whose title stays keeps its line (the world map shows its details, then their rewards
	-- in a frame of their own: QuestMapFrame_ShowQuestDetails).
	local title = QuestInfoTitleHeader
	local home = type(title) == "table" and type(title.GetParent) == "function" and title:GetParent() or nil
	for p, f in pairs(lines) do
		if p ~= home then f:Hide(); f.part, f.anchor = nil, nil end
	end
	local known = type(template) == "table" and PAGES[template] or false
	pages[parent] = known and template or nil -- for Settings' switch, line or none (C.Refresh)
	if not known then return end
	local f = lines[parent]
	if f then f:Hide(); f.part, f.anchor = nil, nil end -- the game placed every part again
	local id
	if template.questLog then id = Try(C_QuestLog and C_QuestLog.GetSelectedQuest) else id = Try(GetQuestID) end
	local text, item, two = C.Line(id)
	local part, anchor = Under(title, parent)
	if not (text and part) then return end
	f = f or NewLine(parent)
	f.quest, f.width = id, tonumber(template.contentWidth) or 275
	Draw(f, text, item, two)
	f:ClearAllPoints()
	f:SetPoint("TOPLEFT", title, "BOTTOMLEFT", 0, -GAP)
	part:ClearAllPoints()
	part:SetPoint(anchor[1] or "TOPLEFT", f, anchor[2] or "BOTTOMLEFT", anchor[3] or 0, -UNDER)
	f.part, f.anchor = part, anchor
	if f.fade:IsPlaying() then f.fade:Stop() end
	f:SetAlpha(1)
	f:Show()
end

-- Settings' Quest Chains changed: the page that has the title gets its line now (shown while the
-- switch was off too), or loses it and has its part back under the title, as the game placed it.
function C.Refresh()
	local title = QuestInfoTitleHeader
	local home = type(title) == "table" and type(title.GetParent) == "function" and title:GetParent() or nil
	if not home then return end
	local f = lines[home]
	if f and f.part then TakeOff(f) end
	if pages[home] and C.On() then C.OnDisplay(pages[home], home) end
end

-- The offer page hides its parts while it types its text in, then fades them in (QuestFrame.lua:590-630).
local function Hide(parent)
	local f = lines[parent]
	if f and f:IsShown() then
		if f.fade:IsPlaying() then f.fade:Stop() end
		f:SetAlpha(0)
	end
end
local function Reveal(parent)
	local f = lines[parent]
	if f then
		if f.fade:IsPlaying() then f.fade:Stop() end
		f:SetAlpha(1)
	end
end
local function FadeIn(parent, time)
	local f = lines[parent]
	if not (f and f:IsShown()) then return end
	f.fade.anim:SetDuration(tonumber(time) or 0.5)
	f.fade:Play()
end

-- The reward's name came in: the line that shows it again, with the game's own link (the part under
-- it follows: it's anchored to the line).
ns.On("GET_ITEM_INFO_RECEIVED", function(_, itemID)
	itemID = tonumber(itemID)
	if not itemID or not waiting[itemID] then return end
	waiting[itemID] = nil
	for _, f in pairs(lines) do
		if f:IsShown() and f.item == itemID then
			local text, item, two = C.Line(f.quest)
			if text then Draw(f, text, item, two) end
		end
	end
end)

if type(hooksecurefunc) == "function" and type(QuestInfo_Display) == "function" then
	local function Safe(fn)
		return function(...)
			local ok, err = pcall(fn, ...)
			if not ok then C.lastError = tostring(err) end
		end
	end
	hooksecurefunc("QuestInfo_Display", Safe(function(template, parent) C.OnDisplay(template, parent) end))
	if type(QuestInfo_HideAlphaDependentText) == "function" then hooksecurefunc("QuestInfo_HideAlphaDependentText", Safe(Hide)) end
	if type(QuestInfo_ShowAlphaDependentText) == "function" then hooksecurefunc("QuestInfo_ShowAlphaDependentText", Safe(Reveal)) end
	if type(QuestInfo_FadeInAlphaDependentText) == "function" then hooksecurefunc("QuestInfo_FadeInAlphaDependentText", Safe(FadeIn)) end
	C.hooked = true
end
