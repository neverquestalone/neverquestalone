-- Chains.lua: where a quest leads. When a quest is a step of a chain that
-- leads to a dungeon, a raid or a rare (or better) reward, one short line
-- under its title, on the page a quest giver offers it on and in the quest
-- log's details, the answer first:
--   Leads to The Deadmines · step 1 of 7
--   Leads to [Whirlwind Axe] or 2 more · step 1 of 6      (the reward's own link, in its quality's colour)
-- Nothing on a quest that leads to none. NeverQuestAlone gets the same facts
-- (Companion.lua's state, Paste.lua's game data): for each quest in the log
-- that has them, and for up to 3 chains the character can start near their
-- level, so it can put a minor-looking first step forward and say why.
--
-- The chains are the emulator's quest data, worked out for every race and
-- class by tools/quest-chains/generate.mjs (the block below; its README has
-- the rules), never the AI's memory. Where a step or a count can't be exact
-- for this character, the line says less ("Leads to ... · step 9", "Leads to
-- ..."), never something false; a reward is one this class can equip.
--
-- It reads the game and draws one line: it never accepts, clicks or moves
-- anything. The line sits in the game's own quest page, by post-hooks
-- (wow-ui-source forever e3ecc27b, 1.60.1.70205; Mainline QuestInfo.lua and
-- QuestFrame.lua, which camelot loads): QuestInfo_Display for the offer page
-- (QUEST_TEMPLATE_DETAIL), the world map's quest log (QUEST_TEMPLATE_MAP_DETAILS)
-- and the quest details window (QUEST_TEMPLATE_LOG). The page lays its parts
-- out top to bottom, each under the last (QuestInfo.lua:107-120), and does it
-- again on every display: the line goes 5 under the title, in the page's own
-- body font and colour (in two when it's wider than the page, the step on a
-- line of its own), and the part that was there 10 under the line (the
-- templates' gap between parts). While the offer page types its text in, it
-- hides its parts until the text is done (QuestFrame.lua:590-630): the line
-- hides and fades in with them (the three AlphaDependentText post-hooks). A
-- page this code doesn't know gets no line. Settings' Quest Chains turns the
-- line off at once; the facts go with the game data either way.

