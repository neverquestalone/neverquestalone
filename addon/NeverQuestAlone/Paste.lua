-- A message of the chat's waiting for a pasted reply: the one with this key,
-- else the newest (what the player asked last), or nil.
function P.Waiting(chat, key)
	local list = type(chat) == "table" and chat.pending or {}
	for i = #list, 1, -1 do
		local p = list[i]
		if p.paste and (key == nil or p.key == key) then return p end
	end
end

-- The newest message waiting for a pasted reply in any chat (Quick questions
-- included, where the HUD's asks go): chat, entry; or nil.
function P.Newest()
	local best, bestChat
	for _, chat in ipairs(ns.db and ns.db.chats or {}) do
		local p = P.Waiting(chat)
		if p and (not best or (p.t or 0) >= (best.t or 0)) then best, bestChat = p, chat end
	end
	return bestChat, best
end

-- The history entry a waiting message came from.
local function EntryOf(chat, p)
	for i = #chat.history, 1, -1 do
		local e = chat.history[i]
		if e.role == "user" and e.key == p.key then return e end
	end
end

local ui = {} -- the Copy and Paste window's parts (below)
local counter = 0
local afterFight -- { chat, key }: a message asked in combat, whose window opens when it ends
-- Chats.Send, once the text is checked: the message waits here for its reply.
-- It isn't the app's (chat.sent stays as it was: a rename or a delete of this
-- chat has nothing to tell an app), and one message waits per chat: a newer
-- one replaces it. In combat the window waits for the fight to end, so no
-- key meant for an ability lands in it.
function P.Send(chat, text, raw, skip, wasBusy)
	counter = counter + 1
	local key = string.format("paste_%d_%d", time(), counter)
	for i = #chat.pending, 1, -1 do
		if chat.pending[i].paste then
			table.remove(chat.pending, i)
			ns.Chats.AddHistory(chat, { role = "system", text = "Replaced by your newer message.", kind = "aborted" })
		end
	end
	table.insert(chat.pending, { key = key, t = time(), paste = true, acked = true })
	ns.Chats.AddHistory(chat, { role = "user", text = text, typed = raw ~= text and raw or nil, key = key, bare = skip or nil })
	if InCombatLockdown() then
		afterFight = { chat = chat.id, key = key }
		ns.Notify.Game(P.Named("Asked NeverQuestAlone: your message opens after the fight."))
	else
		P.Open(chat.id, key)
	end
	ns.Refresh()
	return key
end

