-- The text after the last line that starts with a TL;DR marker ("TL;DR:",
-- "**TL;DR:**", "## TL;DR", "TLDR"), else "".
function P.SplitSummary(text)
	local lines = Lines(Trim(text))
	for k = #lines, 1, -1 do
		local marker = lines[k]:match("^[ \t]*#*[ \t]*[%*_]*[ \t]*[Tt][Ll];?[Dd][Rr][ \t]*:?[ \t]*[%*_]*[ \t]*:?[ \t]*")
		if marker then
			local rest = { lines[k]:sub(#marker + 1) }
			for j = k + 1, #lines do rest[#rest + 1] = lines[j] end
			return Trim(table.concat(rest, "\n"))
		end
	end
	return ""
end

local function FirstSentence(plain)
	for _, line in ipairs(Lines(plain)) do
		if line:match("%S") then
			line = Trim(line)
			local s = line:match("^(.-[%.!%?])%s") or line:match("^(.-[%.!%?])$") or line
			return Shorten(Trim(s), SUMMARY_MAX)
		end
	end
	return ""
end

local BLOCKS = { wowmap = true, wowchips = true, wowrefs = true, wowweights = true }

-- Take the blocks out: returns the text left and { { kind, body }, ... }. A
-- block's fence is a line of its own; an AI page's Copy can drop the last
-- closing fence, so an unclosed block runs to the end. A line that is a bare
-- map command (the fence lost when the reply was copied as shown on the page,
-- not with its Copy button) still draws.
local function TakeBlocks(s)
	local lines, keep, found = Lines(s), {}, {}
	local i = 1
	while i <= #lines do
		local line = lines[i]
		local kind = line:match("^%s*```+%s*(%a+)%s*$")
		kind = kind and kind:lower()
		if kind and BLOCKS[kind] then
			local body, j = {}, i + 1
			while j <= #lines and not lines[j]:match("^%s*```+%s*$") do
				body[#body + 1] = lines[j]
				j = j + 1
			end
			found[#found + 1] = { kind = kind, body = table.concat(body, "\n") }
			keep[#keep + 1] = "" -- where the block was, a paragraph break (as the app leaves it)
			i = j + 1
		elseif line:match('^%s*{%s*"op"%s*:') then
			found[#found + 1] = { kind = "wowmap", body = line }
			i = i + 1
		else
			keep[#keep + 1] = line
			i = i + 1
		end
	end
	return table.concat(keep, "\n"), found
end

-- Suggested replies: plain text, no |, one line each, at most 60 characters.
local function Chips(src)
	local ok, j = P.JSON(src)
	local list = {}
	if ok and P.IsArray(j) then
		list = j
	else
		for _, l in ipairs(Lines(src)) do
			list[#list + 1] = (l:gsub("^%s*[-*]%s+", ""):gsub("^%s*\226\128\162%s+", ""):gsub("^%s*%d+[.)]%s+", ""))
		end
	end
	local out, seen = {}, {}
	for _, s in ipairs(list) do
		if type(s) == "string" then
			local t = Trim(InlinePlain(s):gsub("|", ""):gsub("%s+", " "))
			t = Shorten(t, CHIP_CHARS)
			if t ~= "" and not seen[t] then
				seen[t] = true
				out[#out + 1] = t
			end
			if #out >= CHIPS_MAX then break end
		end
	end
	return #out > 0 and out or nil
end

local REF_KEYS = { q = "q", quest = "q", quests = "q", i = "i", item = "i", items = "i", s = "s", spell = "s", spells = "s" }
