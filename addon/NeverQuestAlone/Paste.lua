-- At login, a message left waiting for an hour or more (a closed game, a
-- reply never pasted) stops waiting, so the HUD and the chat move on.
local STALE = 3600
ns.On("PLAYER_LOGIN", function()
	local ended = false
	for _, chat in ipairs(ns.db and ns.db.chats or {}) do
		for i = #chat.pending, 1, -1 do
			local p = chat.pending[i]
			if p.paste and time() - (tonumber(p.t) or 0) >= STALE then
				table.remove(chat.pending, i)
				ns.Chats.AddHistory(chat, { role = "system", text = "No reply was pasted, so this stopped waiting. Ask again any time.", kind = "aborted" })
				ended = true
			end
		end
	end
	if ended then ns.Refresh() end
end)

-- A pasted reply for the chat's waiting message. Returns true, or false and
-- why ("key": it's shaped like an API key; "ours": the message itself was
-- pasted; "empty"; "none": nothing waits).
function P.Receive(chatId, raw, key)
	-- [code health AD-01] (KY-10) A key pasted here is refused as one typed in the
	-- window is, before anything keeps it: no history, nothing in saved data.
	if ns.Chats.KeyShaped(raw) then return false, "key" end
	local chat = ns.Chats.Find(chatId)
	local p = chat and P.Waiting(chat, key)
	if not p then return false, "none" end
	local r = P.Parse(raw)
	if r.ours then return false, "ours" end
	if r.empty then return false, "empty" end
	local drew = P.ApplyMap(r.map, r.notes)
	local rec = {
		t = "reply", chat = chat.id, mid = "paste:" .. p.key, agent = chat.agent, text = r.text, summary = r.summary, more = r.more,
		chips = r.chips, refs = r.refs, weights = r.weights, drew = #drew > 0 and drew or nil, pasteKey = p.key,
	}
	local note = ns.Chats.ApplyRecord(chat, rec, false)
	if note then ns.Notify.Push({ note }) end
	if P.ShownFor() == chat.id then P.Close() end
	ns.Refresh()
	return true
end

-- Stop waiting for a message of the chat's (this key's, else the newest
-- waiting; Stop, /bones stop): nothing was sent anywhere.
function P.Stop(chat, key)
	for i = #chat.pending, 1, -1 do
		local p = chat.pending[i]
		if p.paste and (key == nil or p.key == key) then
			table.remove(chat.pending, i)
			ns.Chats.AddHistory(chat, { role = "system", text = "Stopped. That message won't get a reply.", kind = "aborted" })
			if P.ShownFor() == chat.id then P.Close() end
			ns.Refresh()
			return true
		end
	end
	return false
end

