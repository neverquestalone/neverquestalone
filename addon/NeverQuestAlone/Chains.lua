-- Race and class ids (UnitRace's and UnitClass's third return) as the templates' mask bits.
local BIT = { 1, 2, 4, 8, 16, 32, 64, 128, 256, 512, 1024, 2048 }
C.STARTS_MAX = 3
local GAP = 5 -- the title to the line (the templates' own gap under a title)
local UNDER = 10 -- the line to the part under it (the templates' gap between parts, QuestInfo.lua:1155, 1195)
local QUALITY = { [3] = "rare", [4] = "epic", [5] = "legendary" }
local QUALITY_HEX = { [3] = "|cff0070dd", [4] = "|cffa335ee", [5] = "|cffff8000" } -- when the game has no ITEM_QUALITY_COLORS

-- The line is on unless Settings' Quest Chains is off.
function C.On()
	local s = ns.db and ns.db.settings
	return not (s and s.chains == false)
end

-- Has a mask this bit (Lua 5.1 has no bit operators; a mask of 0 is everyone)?
local function Has(mask, b)
	mask = tonumber(mask) or 0
	return mask == 0 or (b ~= nil and math.floor(mask / b) % 2 == 1)
end

-- This character's race and class bits; nil for one the client won't say.
local function Bits()
	local raceId = select(3, Try(UnitRace, "player"))
	local classId = select(3, Try(UnitClass, "player"))
	return BIT[tonumber(raceId) or 0], BIT[tonumber(classId) or 0]
end

-- "step of payoff next" and, on a first step, "zone min level exclusive races classes": 0 for unknown.
local parsed = {}
local function Parse(s)
	local r = parsed[s]
	if r ~= nil then return r or nil end
	local n = {}
	for v in s:gmatch("%d+") do n[#n + 1] = tonumber(v) end
	local pay = PAYOFFS[n[3] or 0]
	r = false
	if pay then
		local function Known(v) return v and v > 0 and v or nil end
		r = { step = Known(n[1]), of = Known(n[2]), payoff = pay, next = Known(n[4]) }
		if n[5] then r.zone, r.min, r.level, r.exclusive, r.races, r.classes = Known(n[5]), n[6], n[7], n[8] == 1, n[9], n[10] end
	end
	parsed[s] = r
	return r or nil
end

-- A quest's chain for this character: { step, of (each nil when not exact), payoff (a PAYOFFS entry),
-- next, and on a first step zone, min, level, exclusive, races, classes }; nil when it leads to nothing
-- for them.
function C.For(id, race, class)
	id = tonumber(id)
	local rec = id and STEPS[id]
	if type(rec) == "table" then
		if not (race or class) then race, class = Bits() end
		rec = (rec.class and rec.class[class]) or (rec.race and rec.race[race]) or nil
	end
	if type(rec) ~= "string" then return nil end
	return Parse(rec)
end

-- An area's name as this client has it (C_Map.GetAreaInfo, documented on 1.60.1), kept once it has one.
local areaNames = {}
local function AreaName(id)
	if not id then return nil end
	local n = areaNames[id]
	if not n then
		n = Try(C_Map and C_Map.GetAreaInfo, id)
		n = type(n) == "string" and n ~= "" and n or nil
		areaNames[id] = n -- only a name: the client may not have one yet
	end
	return n
end

-- What a chain leads to, by name: the dungeon or raid as this client names its area, the reward as this
-- client names the item (else the English name the data has).
function C.PayoffName(p)
	if p[1] == "item" then
		local name = Try(C_Item and C_Item.GetItemNameByID, p[2])
		return type(name) == "string" and name ~= "" and name or p[4]
	end
	return AreaName(p[2]) or p[3]
end

-- The reward's link: the game's own, else one in its quality's colour with the name the data has, and a
-- request for the game's (GET_ITEM_INFO_RECEIVED draws the line again).
local waiting = {}
local function QualityHex(p)
	local color = type(ITEM_QUALITY_COLORS) == "table" and ITEM_QUALITY_COLORS[p[3]]
	return type(color) == "table" and type(color.hex) == "string" and color.hex or QUALITY_HEX[p[3]] or "|cffffffff"
end
local function ItemLink(p)
	local _, link = Try(C_Item and C_Item.GetItemInfo, p[2])
	if type(link) == "string" and link:find("|Hitem:", 1, true) then return link end
	waiting[p[2]] = true
	Try(C_Item and C_Item.RequestLoadItemDataByID, p[2])
	return QualityHex(p) .. "|Hitem:" .. ns.Int(p[2]) .. "|h[" .. p[4] .. "]|h|r"
end

-- What the line says the chain leads to: the place, or the reward's link ("or 2 more" when it's one of
-- the rare or better picks this class could take). hex (the HUD's): the place in that colour, and the
-- reward's name in its quality's, not a link (nothing on the HUD takes the mouse).
local function LeadsTo(p, hex)
	if p[1] == "item" then
		local link = hex and (QualityHex(p) .. C.PayoffName(p) .. "|r") or ItemLink(p)
		local more = tonumber(p[5]) or 0
		if more > 0 then return ns.Fill("{link} or {n} more", { link = link, n = ns.Int(more) }) end
		return link
	end
	local name = C.PayoffName(p)
	return hex and (hex .. name .. "|r") or name
end

-- The line under a quest's title, the reward's item id when it names one, the line in two for a page
-- too narrow for it (the step on a line of its own, so a wrap never splits it), and what it leads to
-- ("dungeon", "raid" or "item"); nil for none. hex: the HUD's form (LeadsTo), the place in that colour.
function C.Line(id, hex)
	if not C.On() then return nil end
	local r = C.For(id)
	if not r then return nil end
	local kind = r.payoff[1]
	local item = kind == "item" and r.payoff[2] or nil
	local vars = { to = LeadsTo(r.payoff, hex), step = r.step and ns.Int(r.step), of = r.of and ns.Int(r.of) }
	if r.step and r.of then
		return ns.Fill("Leads to {to} · step {step} of {of}", vars), item, ns.Fill("Leads to {to}\nStep {step} of {of}", vars), kind
	end
	if r.step then return ns.Fill("Leads to {to} · step {step}", vars), item, ns.Fill("Leads to {to}\nStep {step}", vars), kind end
	return ns.Fill("Leads to {to}", vars), item, nil, kind
end

-- The facts NeverQuestAlone gets for a quest, each only when known: step, of, to (the payoff's name),
-- kind (dungeon, raid or reward), item, quality and choice (for a reward: its item, one this class can
-- equip, "rare", "epic" or "legendary", and when it's one of several rare or better picks the class
-- could take, how many), next (the quest after it on the way). nil when it leads to nothing.
function C.Facts(id, race, class)
	local r = C.For(id, race, class)
	if not r then return nil end
	local p = r.payoff
	local f = { step = r.step, of = r.of, to = C.PayoffName(p), next = r.next }
	if p[1] == "item" then
		f.kind, f.item, f.quality = "reward", p[2], QUALITY[p[3]]
		local more = tonumber(p[5]) or 0
		if more > 0 then f.choice = more + 1 end
	else
		f.kind = p[1]
	end
	return f
end

-- The facts in words, for Copy and Paste's game data (Paste.lua): "step 1 of 7, The Deadmines
-- (dungeon), next quest 132", "step 1 of 6, Whirlwind Axe (rare reward, one of 3 to pick from)".
function C.Words(f)
	if type(f) ~= "table" then return "" end
	local what
	if f.kind == "dungeon" or f.kind == "raid" then
		what = ns.Fill("{to} ({kind})", { to = f.to or "", kind = f.kind })
	elseif f.choice then
		what = ns.Fill("{to} ({quality} reward, one of {n} to pick from)", { to = f.to or "", quality = f.quality or "rare", n = ns.Int(f.choice) })
	else
		what = ns.Fill("{to} ({quality} reward)", { to = f.to or "", quality = f.quality or "rare" })
	end
	local v = { step = f.step and ns.Int(f.step), of = f.of and ns.Int(f.of), what = what, next = f.next and ns.Int(f.next) }
	if f.step and f.of then
		return f.next and ns.Fill("step {step} of {of}, {what}, next quest {next}", v) or ns.Fill("step {step} of {of}, {what}", v)
	elseif f.step then
		return f.next and ns.Fill("step {step}, {what}, next quest {next}", v) or ns.Fill("step {step}, {what}", v)
	end
	return f.next and ns.Fill("{what}, next quest {next}", v) or what
end

-- Up to STARTS_MAX chains this character can start now: a first step they haven't done and don't have,
-- that their race and class can take, that their level allows (from 5 levels under theirs to 3 over), and
-- that no quest of an exclusive group can stand in for; those the quest log files under the zone they're
-- in first, then the nearest in level. Each: { id, title (when the client has it; asked for otherwise),
-- level, zone, facts }. inLog: quest id -> true.
function C.Starts(level, inLog)
	level = tonumber(level)
	if not level then return nil end
	local race, class = Bits()
	local here = Try(GetRealZoneText)
	local QL = C_QuestLog or {}
	local found = {}
	for id in pairs(STEPS) do
		local r = C.For(id, race, class)
		if r and r.step == 1 and not r.exclusive and Has(r.races, race) and Has(r.classes, class)
			and r.min and r.min <= level and r.level and r.level <= level + 3 and r.level >= level - 5
			and not (inLog and inLog[id]) and not Try(QL.IsQuestFlaggedCompleted, id) and not Try(QL.IsOnQuest, id) then
			local zone = AreaName(r.zone)
			found[#found + 1] = { id = id, level = r.level, zone = zone, near = (zone and zone == here) and 0 or 1 }
		end
	end
	table.sort(found, function(a, b)
		if a.near ~= b.near then return a.near < b.near end
		local da, dz = math.abs(a.level - level), math.abs(b.level - level)
		if da ~= dz then return da < dz end
		return a.id < b.id
	end)
	local out = {}
	for i = 1, math.min(#found, C.STARTS_MAX) do
		local s = found[i]
		local title = Try(QL.GetTitleForQuestID, s.id)
		if type(title) ~= "string" or title == "" then
			title = nil
			Try(QL.RequestLoadQuestByID, s.id) -- the next state has it
		end
		out[i] = { id = s.id, title = title, level = s.level, zone = s.zone, facts = C.Facts(s.id, race, class) }
	end
	return out
end

