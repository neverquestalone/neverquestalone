-- What a paste or a keystroke put into text that was old: the part that
-- isn't the old text's start or end. When most of the old text is gone, it
-- was selected and replaced, so all of the new text is what came in (a reply
-- that happens to end as the message does keeps its ending).
local function Inserted(old, new)
	local a = 0
	while a < #old and a < #new and old:byte(a + 1) == new:byte(a + 1) do a = a + 1 end
	local b = 0
	while b < #old - a and b < #new - a and old:byte(#old - b) == new:byte(#new - b) do b = b + 1 end
	if a + b < #old / 2 then return new end
	return new:sub(a + 1, #new - b)
end

