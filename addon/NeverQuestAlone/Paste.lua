local Trim, Pipes = ns.Trim, ns.Escape -- (Store.lua; code health AD-14)

-- Characters in UTF-8 text (continuation bytes don't count), as the app counts them.
local function Chars(s) return select(2, tostring(s or ""):gsub("[^\128-\191]", "")) end

-- The first n characters of UTF-8 text.
local function CutChars(s, n)
	s = tostring(s or "")
	local count, i = 0, 1
	while i <= #s do
		local b = s:byte(i)
		if b < 128 or b >= 192 then
			if count == n then return s:sub(1, i - 1) end
			count = count + 1
		end
		i = i + 1
	end
	return s
end

-- At most max characters; past that, cut at a word and end with "…" (the app's rule).
local function Shorten(s, max)
	if Chars(s) <= max then return s end
	local cut = CutChars(s, max - 1)
	cut = cut:gsub("%s+%S*$", "")
	return cut .. "…"
end

local function Lines(s)
	local out = {}
	for line in (tostring(s or "") .. "\n"):gmatch("([^\n]*)\n") do out[#out + 1] = line end
	return out
end

