local function CleanText(v, max)
	if type(v) ~= "string" and type(v) ~= "number" then return "" end
	local s = tostring(v):gsub("[%c|]", " "):gsub("%s+", " ")
	return ns.Utf8Cut(Trim(s), max)
end

-- A stop's note without its distance and proximity claims (protocol.js
-- dropDistanceClaims and DISTANCE_CLAIMS: the same rule, the same list). The
-- HUD shows the stop's live distance above the note; a note that says how far
-- or how close the stop is ("Closest stop, a few steps from you.") was true
-- when the route was planned and goes stale as the player moves. In a clause
-- that makes such a claim only the claim's own words go (what the list
-- matched, a trailing "away" or "ahead", a leading "just", "right", "a" and
-- the like, an "is" or "it's" left hanging at the clause's edge); the clause
-- goes whole only when nothing but stop words is left in it. A note with no
-- claim comes back unchanged, one with nothing else comes back "". A clause
-- with a compass point in it stays, unless the point is of the player ("west
-- of you"). Entries: words in order, whole, after a clause is lowercased and
-- cut to letters, digits and apostrophes; a/b either word, ? optional, # a
-- number, #yd a number run into its unit, ^ the clause's start, $ its end, ~ a
-- distance that stays when the clause says what it's measured from. The list and
-- the words below are protocol.js's own (CLAIMS, the generated block at the top).
P.DISTANCE_CLAIMS = CLAIMS.DISTANCE_CLAIMS
do
	local function Set(list)
		local t = {}
		for _, w in ipairs(list) do t[w] = true end
		return t
	end
	local MEASURED_FROM = Set(CLAIMS.MEASURED_FROM)
	local SELF_WORDS = Set(CLAIMS.SELF_WORDS)
	local COMPASS = Set(CLAIMS.COMPASS)
	-- A claim's own words around what the list matched: after it, and before it.
	local CLAIM_AFTER = Set(CLAIMS.CLAIM_AFTER)
	local CLAIM_BEFORE = Set(CLAIMS.CLAIM_BEFORE)
	-- Words left hanging at a clause's edge once a claim there is gone ("Hezrul is", "it's").
	local HANGING = Set(CLAIMS.HANGING)
	-- What isn't an instruction: stop words and the claims' own vocabulary (numbers neither).
	local NOT_CONTENT = Set(CLAIMS.NOT_CONTENT)
	-- " — ", " – " and "—" among them (UTF-8).
	local SEPS = CLAIMS.CLAUSE_SEPS
	local RULES = {}
	for _, entry in ipairs(P.DISTANCE_CLAIMS) do
		local e, rule = entry, { slots = {} }
		if e:sub(1, 1) == "^" then rule.first, e = true, e:sub(2) end
		if e:sub(-1) == "$" then rule.last, e = true, e:sub(1, -2) elseif e:sub(-1) == "~" then rule.near, e = true, e:sub(1, -2) end
		for w in e:gmatch("%S+") do
			local slot = { alts = {} }
			if w:sub(-1) == "?" then slot.opt, w = true, w:sub(1, -2) end
			if w == "#" then slot.num = true
			elseif w == "#yd" then slot.unit = true
			else for a in w:gmatch("[^/]+") do slot.alts[a] = true end end
			rule.slots[#rule.slots + 1] = slot
		end
		RULES[#RULES + 1] = rule
	end

	-- Bytes of the word character at i: an ASCII letter, digit or ', or a curly apostrophe (3); else 0.
	local function WordChar(s, i)
		if s:find("^[A-Za-z0-9']", i) then return 1 end
		local t = s:sub(i, i + 2)
		if t == "\226\128\152" or t == "\226\128\153" then return 3 end
		return 0
	end

	-- A clause's words, where they are in it (s and e, the first and last byte).
	local function Tokens(s)
		local out, i = {}, 1
		while i <= #s do
			if WordChar(s, i) > 0 then
				local st, buf = i, {}
				while i <= #s do
					local l = WordChar(s, i)
					if l == 0 then break end
					buf[#buf + 1] = l == 3 and "'" or s:sub(i, i)
					i = i + l
				end
				local w = table.concat(buf):lower():gsub("^'+", ""):gsub("'+$", "")
				if w ~= "" then out[#out + 1] = { s = st, e = i - 1, w = w } end
			else
				i = i + 1
			end
		end
		return out
	end

	-- Where the slots from k on, matched from word i, end (one past the last word), or nil.
	local function Match(w, i, slots, k, last)
		if k > #slots then
			if last and i <= #w then return nil end
			return i
		end
		local s, x = slots[k], w[i]
		if x and (s.alts[x] or (s.num and x:find("^%d+$")) or (s.unit and (x:find("^%d+yds?$") or x:find("^%d+yards?$")))) then
			local e = Match(w, i + 1, slots, k + 1, last)
			if e then return e end
		end
		if s.opt then return Match(w, i, slots, k + 1, last) end
		return nil
	end

	local function TrimSpaces(s) return (s:gsub("^ +", ""):gsub(" +$", "")) end

	-- Spaces and punctuation once words are gone from a clause.
	local function Tidy(s)
		return (s:gsub("  +", " "):gsub(" ([,%.;:!%?%)])", "%1"):gsub("%( ", "("):gsub("%(%)", ""):gsub('""', "")
			:gsub("  +", " "):gsub("^[ ,;:]+", ""):gsub("[ ,;:]+$", ""))
	end

	-- A clause without its claims: the same text when it makes none, "" when nothing else is in it.
	local function WithoutClaims(clause)
		local toks = Tokens(clause)
		local w = {}
		for k, t in ipairs(toks) do w[k] = t.w end
		local n = #w
		for k = 1, n do
			if COMPASS[w[k]] and not (w[k + 1] == "of" and SELF_WORDS[w[k + 2] or ""]) then return clause end
		end
		local marked, any = {}, false
		for _, r in ipairs(RULES) do
			for i = 1, r.first and math.min(1, n) or n do
				local e = Match(w, i, r.slots, 1, r.last)
				if e then
					local measured = false
					if r.near then
						for k = 1, n - 1 do
							if (k < i or k >= e) and MEASURED_FROM[w[k]] and not SELF_WORDS[w[k + 1]] then
								measured = true
								break
							end
						end
					end
					if not measured then
						any = true
						for k = i, e - 1 do marked[k] = true end
					end
				end
			end
		end
		if not any then return clause end
		for k = 2, n do
			if marked[k - 1] and not marked[k] and CLAIM_AFTER[w[k]] then marked[k] = true end
		end
		for k = n - 1, 1, -1 do
			if marked[k + 1] and not marked[k] and CLAIM_BEFORE[w[k]] then marked[k] = true end
		end
		if marked[n] then
			local k = n
			while k >= 1 and marked[k] do k = k - 1 end
			while k >= 1 and HANGING[w[k]] do
				marked[k] = true
				k = k - 1
			end
		end
		if marked[1] then
			local k = 1
			while k <= n and marked[k] do k = k + 1 end
			while k <= n and HANGING[w[k]] do
				marked[k] = true
				k = k + 1
			end
		end
		local content = false
		for k = 1, n do
			if not marked[k] and not NOT_CONTENT[w[k]] and not w[k]:find("^%d+$") then content = true end
		end
		if not content then return "" end
		-- Each run of claim words goes, from its first word's start to its last word's end.
		local parts, pos = {}, 1
		for k = 1, n do
			if marked[k] and not marked[k - 1] then
				local j = k
				while j < n and marked[j + 1] do j = j + 1 end
				parts[#parts + 1] = clause:sub(pos, toks[k].s - 1)
				pos = toks[j].e + 1
			end
		end
		parts[#parts + 1] = clause:sub(pos)
		return Tidy(table.concat(parts))
	end

	local function Clauses(body)
		local out, cs, i, sep = {}, 1, 1, ""
		while i <= #body do
			local hit
			for _, x in ipairs(SEPS) do
				if body:sub(i, i + #x - 1) == x then
					hit = x
					break
				end
			end
			if hit then
				out[#out + 1] = { sep = sep, text = body:sub(cs, i - 1) }
				sep, i = hit, i + #hit
				cs = i
			else
				i = i + 1
			end
		end
		out[#out + 1] = { sep = sep, text = body:sub(cs) }
		return out
	end

	function P.DropDistanceClaims(note)
		local s = tostring(note or "")
		if s == "" then return s end
		local changed = false
		-- A parenthesis, as one clause: without its claims, or gone when that's all it held.
		local t = s:gsub("( ?)%(([^()]*)%)", function(space, inner)
			local left = WithoutClaims(inner)
			if left == inner then return nil end
			changed = true
			if left == "" then return "" end
			return space .. "(" .. left .. ")"
		end)
		-- Sentences end at . ! or ? before a space, or at the end.
		local sentences, start = {}, 1
		while true do
			local p = t:find("[%.!%?] ", start)
			if not p then break end
			sentences[#sentences + 1] = t:sub(start, p)
			start = p + 2
		end
		if start <= #t then sentences[#sentences + 1] = t:sub(start) end
		local out = {}
		for _, sentence in ipairs(sentences) do
			local body, stop = sentence:match("^(.-)([%.!%?]*)$")
			local kept, edited = {}, false
			for _, c in ipairs(Clauses(body)) do
				local left = WithoutClaims(c.text)
				if left ~= c.text then edited = true end
				if left ~= "" then kept[#kept + 1] = { sep = c.sep, text = left } end
			end
			if not edited then
				out[#out + 1] = TrimSpaces(sentence)
			else
				changed = true
				local parts = {}
				for k, c in ipairs(kept) do parts[k] = (k > 1 and c.sep or "") .. c.text end
				local str = TrimSpaces(table.concat(parts))
				if str ~= "" then
					str = str:gsub("^[a-z]", string.upper)
					out[#out + 1] = str .. stop
				end
			end
		end
		if not changed then return s end
		return TrimSpaces(table.concat(out, " "))
	end
end

local function Truthy(v) return v ~= nil and v ~= false and v ~= 0 and v ~= "" end
local function Round2(v) return math.floor(v * 100 + 0.5) / 100 end
local function Finite(v) return type(v) == "number" and v == v and v ~= math.huge and v ~= -math.huge end

-- One command, cleaned, or nil (why in notes).
function P.MapCommand(c, notes)
	notes = notes or {}
	if type(c) ~= "table" or P.IsArray(c) then
		notes[#notes + 1] = "a map command isn't an object"
		return nil
	end
	if c.op == "clearall" then return { op = "clearall" } end
	local layer = (type(c.layer) == "string" or type(c.layer) == "number") and tostring(c.layer) or ""
	-- "__proto__" too, as the app refuses it (a name that's a hazard there).
	if #layer < 1 or #layer > MAP.layerName or not layer:match("^[%w_%.%-]+$") or layer == "__proto__" then
		notes[#notes + 1] = "a bad layer name"
		return nil
	end
	if c.op == "clear" then return { op = "clear", layer = layer } end
	if c.op ~= "set" then
		notes[#notes + 1] = "an unknown map command"
		return nil
	end
	if not P.IsArray(c.points) then
		notes[#notes + 1] = "a layer's points aren't a list"
		return nil
	end
	if type(c.title) == "table" then -- junk the app can't read either
		notes[#notes + 1] = "a layer's title isn't text"
		return nil
	end
	local points, noteChars = {}, 0
	for k = 1, math.min(#c.points, MAP.pointsPerLayer) do
		local p = c.points[k]
		local m = type(p) == "table" and tonumber(p.m)
		local x = type(p) == "table" and tonumber(p.x)
		local y = type(p) == "table" and tonumber(p.y)
		if m and m == math.floor(m) and m > 0 and m <= MAP.mapIdMax and Finite(x) and Finite(y) then
			local point = {
				m = m, x = Round2(math.min(100, math.max(0, x))), y = Round2(math.min(100, math.max(0, y))),
				label = CleanText(p.label, MAP.label), kind = KINDS[p.kind] and p.kind or "poi",
			}
			local note = P.DropDistanceClaims(CleanText(p.note, MAP.note))
			if note ~= "" and noteChars + #note <= MAP.layerNotes then
				point.note = note
				noteChars = noteChars + #note
			end
			if type(p.q) == "table" then
				local q, seen = {}, {}
				for _, v in ipairs(p.q) do
					local id = tonumber(v)
					if id and id == math.floor(id) and id > 0 and id < 1e6 and not seen[id] and #q < MAP.quests then
						seen[id] = true
						q[#q + 1] = id
					end
				end
				if #q > 0 then point.q = q end
			end
			points[#points + 1] = point
		end
	end
	if #points == 0 then
		notes[#notes + 1] = "a layer with no usable points"
		return nil
	end
	local title = CleanText((c.title ~= nil and c.title ~= "" and c.title ~= false) and c.title or layer, MAP.title)
	return { op = "set", layer = layer, title = title, ordered = Truthy(c.ordered), loop = Truthy(c.loop), points = points }
end

-- The map's layers now, in the form commands make, oldest first.
local function CurrentLayers()
	local list = {}
	local m = type(NQAMapDB) == "table" and NQAMapDB.map
	for _, l in ipairs(type(m) == "table" and type(m.layers) == "table" and m.layers or {}) do
		if type(l) == "table" and type(l.name) == "string" and type(l.points) == "table" then
			local points = {}
			for _, p in ipairs(l.points) do
				if type(p) == "table" then
					points[#points + 1] = { m = p[1], x = p[2], y = p[3], label = p[4], kind = p[5],
						note = (type(p[6]) == "string" and p[6] ~= "") and p[6] or nil, q = type(p[7]) == "table" and p[7] or nil }
				end
			end
			list[#list + 1] = { name = l.name, title = l.title, ordered = l.ordered, loop = l.loop, points = points }
		end
	end
	return list, m
end

-- Apply commands to the map. Returns the names of the layers they drew that
-- are on the map after them, in the order drawn (a reply's drew), and notes.
function P.ApplyMap(cmds, notes)
	notes = notes or {}
	local layers, cur = CurrentLayers()
	local changed, drew = false, {}
	local function find(name)
		for k, l in ipairs(layers) do
			if l.name == name then return k end
		end
	end
	for _, raw in ipairs(cmds or {}) do
		local c = P.MapCommand(raw, notes)
		if c and c.op == "clearall" then
			if #layers > 0 then layers, changed = {}, true end
		elseif c and c.op == "clear" then
			local k = find(c.layer)
			if k then
				table.remove(layers, k)
				changed = true
			end
		elseif c then
			local k = find(c.layer)
			if k then table.remove(layers, k) end
			layers[#layers + 1] = { name = c.layer, title = c.title, ordered = c.ordered, loop = c.loop, points = c.points }
			changed = true
			drew[#drew + 1] = c.layer
		end
	end
	-- Within the budget: the oldest layers go first, then the oldest layers' notes.
	local function total()
		local n = 0
		for _, l in ipairs(layers) do n = n + #l.points end
		return n
	end
	while #layers > MAP.layers or total() > MAP.totalPoints do
		table.remove(layers, 1)
		changed = true
	end
	local function noteChars()
		local n = 0
		for _, l in ipairs(layers) do
			for _, p in ipairs(l.points) do n = n + (p.note and #p.note or 0) end
		end
		return n
	end
	for _, l in ipairs(layers) do
		if noteChars() <= MAP.mapNotes then break end
		for _, p in ipairs(l.points) do p.note = nil end
	end
	if not changed then return {}, notes end
	local out = {}
	for _, l in ipairs(layers) do
		local points = {}
		for _, p in ipairs(l.points) do
			local row = { p.m, p.x, p.y, p.label or "", p.kind or "poi" }
			if p.note or p.q then row[6] = p.note or "" end
			if p.q then row[7] = p.q end
			points[#points + 1] = row
		end
		out[#out + 1] = { name = l.name, title = l.title, ordered = l.ordered and true or false, loop = l.loop and true or false, points = points }
	end
	local version = (type(cur) == "table" and cur.epoch == EPOCH and tonumber(cur.version) or 0) + 1
	if type(NQAMap) == "table" and type(NQAMap.Sync) == "function" then
		pcall(NQAMap.Sync, { epoch = EPOCH, version = version, layers = out })
	end
	-- Drawn and still there, once each, in order (the reply's drew; Chats.CleanDrew caps it).
	local on, list, seen = {}, {}, {}
	for _, l in ipairs(layers) do on[l.name] = true end
	for _, name in ipairs(drew) do
		if on[name] and not seen[name] then
			seen[name] = true
			list[#list + 1] = name
		end
	end
	return list, notes
end

---------------------------------------------------------------------------
-- A pasted reply, read: { text, summary, more, chips, refs, weights, map,
-- notes, empty, ours }. text and summary are ready to show (| doubled).
---------------------------------------------------------------------------

function P.Parse(raw)
	raw = ns.Utf8Cut(tostring(raw or ""), PASTE_MAX):gsub("\r\n?", "\n")
	local out = { notes = {}, map = {} }
	if not raw:match("%S") then
		out.empty = true
		return out
	end
	-- The message from step 1, whole or in part (its mark, or how its instructions start).
	if raw:find(P.MARK, 1, true) or raw:find(Instructions():sub(1, 40), 1, true) then
		out.ours = true
		return out
	end
	local text, found = TakeBlocks(raw)
	for _, b in ipairs(found) do
		if b.kind == "wowmap" then
			MapCommands(b.body, out.map, out.notes)
		elseif b.kind == "wowchips" then
			out.chips = Chips(Trim(b.body)) or out.chips
		elseif b.kind == "wowrefs" then
			out.refs = Refs(Trim(b.body)) or out.refs
		elseif b.kind == "wowweights" then
			out.weights = Weights(Trim(b.body)) or out.weights
		end
	end
	text = Trim(text:gsub("\n\n\n+", "\n\n"))
	local shown = P.Markdown(text)
	local summary = P.SplitSummary(text)
	if summary ~= "" then
		summary = Trim(InlinePlain((summary:gsub("%s*\n%s*", " "))))
	else
		summary = FirstSentence((shown:gsub("|c%x%x%x%x%x%x%x%x", ""):gsub("|r", ""):gsub("||", "|")))
	end
	out.summary = Pipes(Shorten(summary, SUMMARY_MAX))
	out.more = 0
	if #shown > TEXT_MAX then
		-- At a line break near the limit, never inside an escape or a character.
		-- [code health AD-02] The last line break, grey and close: anchored, so a text with
		-- none is one look, not one from every byte (12,000 squared, seconds in the game).
		local cut = TEXT_MAX
		local nl = shown:sub(1, TEXT_MAX):match("^.*()\n")
		if nl and nl > TEXT_MAX - 2000 then cut = nl - 1 end
		local head = ns.Utf8Cut(shown, cut)
		while head:sub(-1) == "|" do head = head:sub(1, -2) end
		out.more = #shown - #head
		if (head:match("^.*()" .. GRAY:gsub("|", "%%|")) or 0) > (head:match("^.*()|r") or 0) then head = head .. CLOSE end
		shown = head
	end
	out.text = shown
	out.empty = shown == "" and #out.map == 0 and not out.chips and not out.refs and not out.weights
	return out
end

