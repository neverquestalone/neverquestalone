-- (UpdateTooltip). A shift- or ctrl-click does what it does on them (HandleModifiedItemClick: the link
-- into chat, the Dressing Room).
local function LinkEnter(self, link)
	if not GameTooltip then return end
	GameTooltip:SetOwner(self, "ANCHOR_CURSOR_RIGHT")
	if not pcall(GameTooltip.SetHyperlink, GameTooltip, link) then return end
	if type(GameTooltip_ShowCompareItem) == "function" then pcall(GameTooltip_ShowCompareItem, GameTooltip) end
	GameTooltip:Show()
	self.UpdateTooltip = function(owner) LinkEnter(owner, link) end
end
local function LinkLeave(self)
	self.UpdateTooltip = nil
	if GameTooltip then GameTooltip:Hide() end
end
local function LinkClick(_, _, text)
	if type(IsModifiedClick) == "function" and IsModifiedClick() and type(HandleModifiedItemClick) == "function" then
		pcall(HandleModifiedItemClick, text)
	end
end

local function NewLine(parent)
