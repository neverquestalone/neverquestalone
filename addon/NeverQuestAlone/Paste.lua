local function Id(v)
	if type(v) == "string" and v:match("^%d+$") then v = tonumber(v) end
	if type(v) == "number" and v == math.floor(v) and v > 0 and v < 2147483647 then return v end
end

-- Game references: whole ids, 8 of each kind at most.
local function Refs(src)
	local ok, j = P.JSON(src)
	local out, any = {}, false
	local function add(k, v)
		local id = Id(v)
		if not id then return end
		out[k] = out[k] or {}
		for _, x in ipairs(out[k]) do
			if x == id then return end
		end
		if #out[k] < REFS_MAX then
			out[k][#out[k] + 1] = id
			any = true
		end
	end
	if ok and type(j) == "table" and not P.IsArray(j) then
		local lower = {}
		for k, v in pairs(j) do
			if type(k) == "string" then lower[k:lower()] = v end
		end
		for _, key in ipairs(REF_ORDER) do
			local v = lower[key]
			if type(v) == "table" then
				for _, x in ipairs(v) do add(REF_KEYS[key], x) end
			elseif v ~= nil then
				add(REF_KEYS[key], v)
			end
		end
	else
		for _, line in ipairs(Lines(src)) do
			local word, ids = Trim(line):match("^(%a+)%s*[:=]?%s*([%d,%s]+)$")
			local kind = word and REF_KEYS[word:lower()]
			if kind then
				for x in ids:gmatch("%d+") do add(kind, x) end
			end
		end
	end
	return any and out or nil
end

-- Stat weights under the keys the addon knows, finite numbers under 100.
local function Weights(src)
	local ok, j = P.JSON(src)
	if not ok or type(j) ~= "table" or P.IsArray(j) then return nil end
	local out, any = {}, false
	for k, v in pairs(j) do
		local key = type(k) == "string" and k:lower() or nil
		if key and ns.WEIGHT_KEYS[key] and type(v) == "number" and v == v and v > -100 and v < 100 then
			out[key] = v
			any = true
		end
	end
	return any and out or nil
end

-- Map commands from a wowmap block: one value (an object or a list), else one per line.
local function MapCommands(src, into, notes)
	local ok, v = P.JSON(Trim(src))
	if ok and type(v) == "table" then
		if P.IsArray(v) then
			for _, c in ipairs(v) do into[#into + 1] = c end
		else
			into[#into + 1] = v
		end
		return
	end
	for _, line in ipairs(Lines(src)) do
		if line:match("%S") then
			local lok, c = P.JSON(line)
			if lok and c ~= nil then into[#into + 1] = c else notes[#notes + 1] = "unreadable wowmap line" end
		end
	end
end

